#!/usr/bin/env node
import fs from "node:fs";
import { withExistingStorageReadLock, resolveStorage, readStorageContext, ensureStorage, validateContainedPath, withStorageLock } from "./storage-paths.mjs";
import { isImportPathVisible } from "./state-import.mjs";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { sha256, validateLocalIssueRecord } from "./incident-state.mjs";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_CONFIG = {
  issue_sync_mode: "confirm-github",
  issue_sync_public_repo_policy: "block-sensitive"
};
const ISSUE_SYNC_MODES = new Set(["off", "draft-local", "confirm-github", "auto-github"]);
const PUBLIC_REPO_POLICIES = new Set(["block-sensitive", "confirm-sensitive", "allow"]);
const EXTERNAL_ID_MARKER_PREFIX = "AIVV-External-ID:";
const CLOSURE_RECOMMENDATION_ID_PREFIX = "AIVV-Closure-Recommendation-ID:";
const CLOSURE_RECOMMENDATION_HASH_PREFIX = "AIVV-Closure-Recommendation-Hash:";
const MAX_REMOTE_MATCHES = 20;
const MAX_REMOTE_COMMENTS = 20;
const GITHUB_LABEL_ALLOWLIST = new Set([
  "incident-followup", "problem", "corrective-action", "preventive-action",
  "detection-action", "blocked", "security-sensitive", "provider", "viewer", "runtime"
]);

function parseArgs(argv) {
  const parsed = { _: [] };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (!arg.startsWith("--")) {
      parsed._.push(arg);
      continue;
    }
    const key = arg.slice(2);
    const value = argv[i + 1];
    if (value === undefined || value.startsWith("--")) {
      parsed[key] = true;
    } else {
      parsed[key] = value;
      i += 1;
    }
  }
  return parsed;
}

function writeJson(value, status = 0) {
  process.stdout.write(`${JSON.stringify(value)}\n`);
  process.exit(status);
}

function readJsonFile(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function renderIssueBody(issue) {
  return [
    `${EXTERNAL_ID_MARKER_PREFIX} ${issue.external_id}`,
    "",
    issue.title,
    "",
    "## Summary",
    issue.acceptance_criteria.length > 0 ? "Lifecycle follow-up generated by AIVV." : "AIVV lifecycle follow-up.",
    "",
    "## Acceptance Criteria",
    ...issue.acceptance_criteria.map((item) => `- ${item}`),
    "",
    "## Closure Criteria",
    ...issue.closure_criteria.map((item) => `- ${item}`),
    "",
    "## Linked Lifecycle Records",
    ...issue.links.map((link) => `- ${link.type}: ${link.id} (${link.role})`),
    "",
    "## Sync Metadata",
    `- Local issue: ${issue.id}`,
    `- External id: ${issue.external_id}`
  ].join("\n");
}

function bodyHash(body) {
  return sha256(body);
}

function issueIsSensitive(issue) {
  return (issue.evidence || []).some((entry) =>
    entry.local_only === true ||
    entry.publishable === false ||
    (Array.isArray(entry.redactions_applied) && entry.redactions_applied.length > 0)
  );
}

function resolveConfig(configJsonText) {
  let parsed = {};
  if (configJsonText) parsed = JSON.parse(configJsonText);
  const config = {
    issue_sync_mode: parsed.issue_sync_mode || DEFAULT_CONFIG.issue_sync_mode,
    issue_sync_public_repo_policy: parsed.issue_sync_public_repo_policy || DEFAULT_CONFIG.issue_sync_public_repo_policy
  };
  if (!ISSUE_SYNC_MODES.has(config.issue_sync_mode) || !PUBLIC_REPO_POLICIES.has(config.issue_sync_public_repo_policy)) {
    const error = new Error("invalid-config");
    error.code = "invalid-config";
    throw error;
  }
  return config;
}

function ghBin() {
  return process.env.AIVV_GH_BIN || "gh";
}

function runGh(args, input = "") {
  const result = spawnSync(ghBin(), args, { input, encoding: "utf8" });
  if (result.status !== 0) {
    return { ok: false, status: result.status, stderr: result.stderr, stdout: result.stdout };
  }
  return { ok: true, stdout: result.stdout, stderr: result.stderr };
}

function assertGhAvailable() {
  const result = runGh(["auth", "status"]);
  if (!result.ok) return { ok: false, reason: "gh-unavailable" };
  return { ok: true };
}

function parseRepo(value) {
  const match = /^([^/]+)\/([^/]+)$/.exec(value || "");
  if (!match) return null;
  return { owner: match[1], repo: match[2].replace(/\.git$/, "") };
}

function parseGithubRemote(value) {
  const https = /^https:\/\/github\.com\/([^/]+)\/(.+?)(?:\.git)?$/.exec(value || "");
  if (https) return { owner: https[1], repo: https[2].replace(/\.git$/, "") };
  const ssh = /^git@github\.com:([^/]+)\/(.+?)(?:\.git)?$/.exec(value || "");
  if (ssh) return { owner: ssh[1], repo: ssh[2].replace(/\.git$/, "") };
  return null;
}

function resolveRepo(repoArg) {
  if (repoArg) return parseRepo(repoArg);
  // Installed-plugin limitation: cwd REPO_ROOT resolves the plugin checkout's own origin remote, not the target project's — pass --repo explicitly when reviewing another project.
  const remote = spawnSync("git", ["remote", "get-url", "origin"], { cwd: REPO_ROOT, encoding: "utf8" });
  if (remote.status !== 0) return null;
  return parseGithubRemote(remote.stdout.trim());
}

function parseGhJson(result, fallback) {
  try {
    return JSON.parse(result.stdout || fallback);
  } catch {
    return null;
  }
}

function normalizeComments(comments) {
  if (!Array.isArray(comments)) return [];
  return comments.slice(0, MAX_REMOTE_COMMENTS).map((comment) => ({ body: String(comment.body || "") }));
}

function repoVisibility(repo) {
  const result = runGh(["repo", "view", `${repo.owner}/${repo.repo}`, "--json", "visibility"]);
  if (!result.ok) return { ok: false, reason: "gh-unavailable" };
  const parsed = parseGhJson(result, "{}");
  if (!parsed) return { ok: false, reason: "invalid-gh-json" };
  return { ok: true, visibility: String(parsed.visibility || "PRIVATE").toUpperCase() };
}

function exactMarker(issue) {
  return `${EXTERNAL_ID_MARKER_PREFIX} ${issue.external_id}`;
}

function ghIssueView(repo, number) {
  const result = runGh(["issue", "view", String(number), "--repo", `${repo.owner}/${repo.repo}`, "--json", "body,comments"]);
  if (!result.ok) return { ok: false, reason: "gh-unavailable" };
  const parsed = parseGhJson(result, "{}");
  if (!parsed || typeof parsed !== "object") return { ok: false, reason: "invalid-gh-json" };
  if (Array.isArray(parsed.comments) && parsed.comments.length > MAX_REMOTE_COMMENTS) {
    return { ok: false, blocked: true, reason: "remote-result-cap-exceeded" };
  }
  return { ok: true, body: String(parsed.body || ""), comments: normalizeComments(parsed.comments) };
}

function ghIssueList(repo, search) {
  const result = runGh(["issue", "list", "--repo", `${repo.owner}/${repo.repo}`, "--state", "all", "--search", search, "--json", "number,url,title,body"]);
  if (!result.ok) return { ok: false, reason: "gh-unavailable" };
  const parsed = parseGhJson(result, "[]");
  if (!Array.isArray(parsed)) return { ok: false, reason: "invalid-gh-json" };
  if (parsed.length > MAX_REMOTE_MATCHES) return { ok: false, blocked: true, reason: "remote-result-cap-exceeded" };
  return { ok: true, issues: parsed };
}

function actionTitleFingerprint(issue) {
  return issue.title.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
}

function issueDuplicateKeys(issue) {
  return [
    issue.id,
    issue.external_id,
    ...issue.links.filter((link) => ["incident", "problem", "problem_cluster"].includes(link.type)).map((link) => link.id),
    ...issue.links.filter((link) => link.role === "recurrence-key").map((link) => link.id),
    actionTitleFingerprint(issue)
  ].filter(Boolean);
}

function containsText(haystack, needle) {
  return String(haystack || "").toLowerCase().includes(String(needle || "").toLowerCase());
}

function likelyDuplicateIssues(issue, issues) {
  const fingerprint = actionTitleFingerprint(issue);
  const keys = issueDuplicateKeys(issue).filter((key) => key !== fingerprint);
  return issues.filter((candidate) => {
    const titleBody = `${candidate.title || ""}\n${candidate.body || ""}`;
    return containsText(titleBody, fingerprint) && keys.some((key) => containsText(titleBody, key));
  }).map((candidate) => ({ number: candidate.number, url: candidate.url }));
}

function findRemoteIssue(issue, repo) {
  const byExternalId = ghIssueList(repo, issue.external_id);
  if (!byExternalId.ok) return byExternalId;
  const marked = byExternalId.issues.filter((candidate) => String(candidate.body || "").includes(exactMarker(issue)));
  if (marked.length === 1) return { ok: true, operation: "update", issue: marked[0] };
  if (marked.length > 1) return { ok: true, blocked: true, reason: "external-id-ambiguous" };

  const byFingerprint = ghIssueList(repo, actionTitleFingerprint(issue));
  if (!byFingerprint.ok) return byFingerprint;
  const matches = likelyDuplicateIssues(issue, byFingerprint.issues);
  if (matches.length > 0) return { ok: true, blocked: true, reason: "likely-duplicate-github-issue", matches };
  return { ok: true, operation: "create" };
}

function validationOptions(options, issueFile) {
  let stateDir = options["state-dir"] ? path.resolve(options["state-dir"]) : undefined;
  if (!stateDir) {
    const issueDir = path.dirname(path.resolve(issueFile));
    if (path.basename(issueDir) === "issues") stateDir = path.dirname(issueDir);
  }
  return { stateDir, file: issueFile ? path.resolve(issueFile) : undefined };
}

function loadIssue(file, options = {}) {
  const issue = readJsonFile(file);
  const validation = validateLocalIssueRecord(issue, validationOptions(options, file));
  if (validation.status !== "valid") {
    const error = new Error(validation.reason);
    error.validation = validation;
    throw error;
  }
  return issue;
}

function updateConflict(issue, repo, number) {
  const remoteView = ghIssueView(repo, number);
  if (!remoteView.ok) return { ok: false, reason: remoteView.reason };
  if (!remoteView.body.includes(exactMarker(issue))) {
    return { ok: true, blocked: true, reason: "external-id-marker-missing" };
  }
  if (issue.sync?.status === "synced" && issue.sync.sync_hash && issue.sync.sync_hash !== bodyHash(remoteView.body)) {
    return { ok: true, blocked: true, reason: "remote-body-conflict" };
  }
  return { ok: true, remote_body_hash: bodyHash(remoteView.body), comments: remoteView.comments };
}

function planIssue(issue, options) {
  const body = renderIssueBody(issue);
  const config = resolveConfig(options["config-json"]);
  const base = {
    status: "planned",
    operation: "none",
    requires_confirmation: false,
    remote_allowed: false,
    reason: null,
    external_id: issue.external_id,
    body_hash: bodyHash(body)
  };

  if (config.issue_sync_mode === "off" || config.issue_sync_mode === "draft-local") return base;

  const ghAvailable = assertGhAvailable();
  if (!ghAvailable.ok) return { ...base, status: "blocked", reason: ghAvailable.reason };
  const repo = resolveRepo(options.repo);
  if (!repo) return { ...base, status: "blocked", reason: "repo-unresolved" };
  const visibility = repoVisibility(repo);
  if (!visibility.ok) return { ...base, status: "blocked", reason: visibility.reason };

  const sensitive = issueIsSensitive(issue);
  if (visibility.visibility === "PUBLIC" && sensitive) {
    if (config.issue_sync_public_repo_policy === "block-sensitive") {
      return { ...base, status: "blocked", reason: "sensitive-publication-blocked" };
    }
    if (config.issue_sync_public_repo_policy === "confirm-sensitive" && options["confirm-sensitive"] !== true) {
      return { ...base, status: "blocked", reason: "sensitive-confirmation-required" };
    }
  }

  if (issue.status === "closed" && issue.sync.status === "synced") {
    const number = issue.sync.github?.number;
    if (!number) return { ...base, status: "blocked", reason: "github-issue-number-missing" };
    const remoteView = ghIssueView(repo, number);
    if (!remoteView.ok) return { ...base, status: "blocked", reason: remoteView.reason };
    if (!remoteView.body.includes(exactMarker(issue))) {
      return { ...base, status: "blocked", reason: "external-id-marker-missing" };
    }
    if (issue.sync.sync_hash && issue.sync.sync_hash !== bodyHash(remoteView.body)) {
      return { ...base, status: "blocked", reason: "remote-body-conflict" };
    }
    return {
      ...base,
      operation: "closure-recommendation",
      remote_body_hash: bodyHash(remoteView.body),
      requires_confirmation: config.issue_sync_mode === "confirm-github",
      remote_allowed: true
    };
  }

  const remote = findRemoteIssue(issue, repo);
  if (!remote.ok) return { ...base, status: remote.blocked ? "blocked" : "blocked", reason: remote.reason };
  if (remote.blocked) return { ...base, status: "blocked", reason: remote.reason, matches: remote.matches };
  if (remote.operation === "update" && issue.sync?.status === "synced") {
    const conflict = updateConflict(issue, repo, remote.issue?.number);
    if (!conflict.ok) return { ...base, status: "blocked", reason: conflict.reason };
    if (conflict.blocked) return { ...base, status: "blocked", reason: conflict.reason };
  }

  return {
    ...base,
    operation: remote.operation,
    github_issue: remote.issue ? { number: remote.issue.number, url: remote.issue.url } : null,
    requires_confirmation: config.issue_sync_mode === "confirm-github",
    remote_allowed: true
  };
}

function issueLabels(issue) {
  return (issue.labels || []).filter((label) => GITHUB_LABEL_ALLOWLIST.has(label));
}

function tempFile(prefix, content) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), `${prefix}-`));
  fs.chmodSync(dir, 0o700);
  const file = path.join(dir, "body.md");
  fs.writeFileSync(file, content, { mode: 0o600 });
  return file;
}

function parseIssueNumberFromUrl(url) {
  const match = /\/issues\/(\d+)\s*$/.exec(String(url || "").trim());
  return match ? Number(match[1]) : null;
}

function persistSyncStatus(issue, issueFile, status, stateDir) {
  const next = structuredClone(issue);
  next.sync.status = status;
  next.sync.last_checked_at = new Date().toISOString();
  const validation = validateLocalIssueRecord(next, validationOptions({ "state-dir": stateDir }, issueFile));
  if (validation.status !== "valid") {
    return { ok: false, validation };
  }
  fs.writeFileSync(issueFile, `${JSON.stringify(next, null, 2)}\n`);
  return { ok: true, issue: next };
}

function closureRecommendationId(issue) {
  return `${CLOSURE_RECOMMENDATION_ID_PREFIX} ${issue.external_id}`;
}

function closureRecommendationBodyWithoutHash(issue) {
  return [
    "## AIVV Closure Recommendation",
    "",
    closureRecommendationId(issue),
    "",
    `Local issue \`${issue.id}\` has satisfied its closure gates.`,
    "",
    "Recommended action: close this GitHub issue after user confirmation.",
    "",
    "Closure rationale:",
    issue.closure_decision?.rationale || ""
  ].join("\n");
}

function closureRecommendationBody(issue) {
  const withoutHash = closureRecommendationBodyWithoutHash(issue);
  const hash = bodyHash(withoutHash);
  return withoutHash.replace(closureRecommendationId(issue), `${closureRecommendationId(issue)}\n${CLOSURE_RECOMMENDATION_HASH_PREFIX} ${hash}`);
}

function closureRecommendationHash(issue) {
  return bodyHash(closureRecommendationBodyWithoutHash(issue));
}

function closureRecommendationAlreadyPresent(issue, comments) {
  const id = closureRecommendationId(issue);
  const hashLine = `${CLOSURE_RECOMMENDATION_HASH_PREFIX} ${closureRecommendationHash(issue)}`;
  return comments.some((comment) => comment.body.includes(id) && comment.body.includes(hashLine));
}

function applyClosureRecommendation(issue, issueFile, options, repo, plan) {
  const view = ghIssueView(repo, issue.sync.github?.number);
  if (!view.ok) {
    persistSyncStatus(issue, issueFile, "sync-failed", options["state-dir"]);
    return { result: { status: "blocked", reason: view.reason || "sync-failed", operation: "closure-recommendation" }, status: 0 };
  }
  if (!view.body.includes(exactMarker(issue))) {
    persistSyncStatus(issue, issueFile, "conflict", options["state-dir"]);
    return { result: { status: "blocked", reason: "external-id-marker-missing", operation: "closure-recommendation" }, status: 0 };
  }
  if (issue.sync.sync_hash && issue.sync.sync_hash !== bodyHash(view.body)) {
    persistSyncStatus(issue, issueFile, "conflict", options["state-dir"]);
    return { result: { status: "blocked", reason: "remote-body-conflict", operation: "closure-recommendation" }, status: 0 };
  }
  if (closureRecommendationAlreadyPresent(issue, view.comments)) {
    return {
      result: {
        ...plan,
        status: "applied",
        closure_recommendation_posted: false,
        reason: "closure-recommendation-already-present",
        github_close_performed: false
      },
      status: 0
    };
  }

  const commentFile = tempFile("aivv-closure-recommendation", closureRecommendationBody(issue));
  try {
    const result = runGh(["issue", "comment", String(issue.sync.github.number), "--repo", `${repo.owner}/${repo.repo}`, "--body-file", commentFile]);
    if (!result.ok) {
      persistSyncStatus(issue, issueFile, "sync-failed", options["state-dir"]);
      return { result: { status: "blocked", reason: "gh-comment-failed", operation: "closure-recommendation" }, status: 0 };
    }
  } finally {
    fs.rmSync(commentFile, { force: true });
    fs.rmdirSync(path.dirname(commentFile));
  }

  return {
    result: {
      ...plan,
      status: "applied",
      closure_recommendation_posted: true,
      github_close_performed: false
    },
    status: 0
  };
}

function applyIssue(issue, issueFile, options) {
  const plan = planIssue(issue, options);
  if (plan.status === "blocked") {
    if (options.confirm === true && issue.sync?.status === "synced" && ["external-id-marker-missing", "remote-body-conflict"].includes(plan.reason)) {
      persistSyncStatus(issue, issueFile, "conflict", options["state-dir"]);
    }
    return { result: plan, status: 0 };
  }
  if (plan.operation === "none") return { result: { ...plan, status: "applied" }, status: 0 };
  if (plan.requires_confirmation && options.confirm !== true) {
    return { result: { status: "blocked", reason: "confirmation-required", operation: plan.operation }, status: 2 };
  }

  const repo = resolveRepo(options.repo);
  if (!repo) return { result: { status: "blocked", reason: "repo-unresolved" }, status: 0 };
  if (plan.operation === "closure-recommendation") {
    return applyClosureRecommendation(issue, issueFile, options, repo, plan);
  }
  if (!["create", "update"].includes(plan.operation)) {
    return { result: { status: "blocked", reason: "operation-not-implemented", operation: plan.operation }, status: 0 };
  }
  const body = renderIssueBody(issue);
  const bodyFile = tempFile("aivv-issue-body", body);
  const labels = issueLabels(issue).flatMap((label) => ["--label", label]);
  let number = plan.github_issue?.number ?? issue.sync.github?.number ?? null;

  try {
    if (plan.operation === "create") {
      const result = runGh(["issue", "create", "--repo", `${repo.owner}/${repo.repo}`, "--title", issue.title, "--body-file", bodyFile, ...labels]);
      if (!result.ok) {
        persistSyncStatus(issue, issueFile, "sync-failed", options["state-dir"]);
        return { result: { status: "blocked", reason: "gh-create-failed" }, status: 0 };
      }
      number = parseIssueNumberFromUrl(result.stdout);
      if (!number) return { result: { status: "blocked", reason: "gh-create-number-unresolved" }, status: 0 };
    } else if (plan.operation === "update") {
      if (!number) return { result: { status: "blocked", reason: "github-issue-number-missing" }, status: 0 };
      if (issue.sync?.status === "synced") {
        const conflict = updateConflict(issue, repo, number);
        if (!conflict.ok) {
          persistSyncStatus(issue, issueFile, "sync-failed", options["state-dir"]);
          return { result: { status: "blocked", reason: conflict.reason || "sync-failed" }, status: 0 };
        }
        if (conflict.blocked) {
          persistSyncStatus(issue, issueFile, "conflict", options["state-dir"]);
          return { result: { status: "blocked", reason: conflict.reason }, status: 0 };
        }
      }
      const result = runGh(["issue", "edit", String(number), "--repo", `${repo.owner}/${repo.repo}`, "--title", issue.title, "--body-file", bodyFile]);
      if (!result.ok) {
        persistSyncStatus(issue, issueFile, "sync-failed", options["state-dir"]);
        return { result: { status: "blocked", reason: "gh-edit-failed" }, status: 0 };
      }
    }
  } finally {
    fs.rmSync(bodyFile, { force: true });
    fs.rmdirSync(path.dirname(bodyFile));
  }

  const nowIso = new Date().toISOString();
  issue.body_hash = bodyHash(body);
  issue.sync.status = "synced";
  issue.sync.github = { host: "github.com", owner: repo.owner, repo: repo.repo, number };
  issue.sync.last_synced_at = nowIso;
  issue.sync.last_checked_at = nowIso;
  issue.sync.sync_hash = issue.body_hash;
  const validation = validateLocalIssueRecord(issue, validationOptions(options, issueFile));
  if (validation.status !== "valid") return { result: { status: "blocked", reason: "local-issue-invalid-after-sync", validation }, status: 0 };
  fs.writeFileSync(issueFile, `${JSON.stringify(issue, null, 2)}\n`);
  return { result: { ...plan, status: "applied", operation: plan.operation, github_issue: { number } }, status: 0 };
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const command = args._[0];
  if (!command || !args.issue) writeJson({ status: "invalid-args", reason: "missing-command-or-issue" }, 64);

  let issue;
  try {
    const file = path.resolve(args.issue);
    let stateDir = args["state-dir"] ? path.resolve(args["state-dir"]) : path.dirname(file);
    if (["issues", "archive"].includes(path.basename(stateDir))) stateDir = path.dirname(stateDir);
    if (path.basename(stateDir) === "archive") stateDir = path.dirname(stateDir);
    const context = { target_dir: path.dirname(stateDir) };
    issue = fs.existsSync(path.join(context.target_dir, "target.json"))
      ? withExistingStorageReadLock(context, () => loadIssue(args.issue, args)) : loadIssue(args.issue, args);
    if (!issue) throw new Error("selected-namespace-missing");
  } catch (error) {
    writeJson({ status: "invalid-issue", reason: error.validation?.reason || error.message, detail: error.validation?.detail }, 64);
  }

  if (command === "render-body") {
    process.stdout.write(renderIssueBody(issue));
    return;
  }

  try {
    if (command === "plan") {
      writeJson(planIssue(issue, args));
    }
    if (command === "apply") {
      const context = args.context ? readStorageContext(args.context) : resolveStorage({ target: args.target });
      if (args.target && fs.realpathSync(path.resolve(args.target)) !== context.target) throw new Error("storage-context-target-mismatch");
      if (args["state-dir"] && path.resolve(args["state-dir"]) !== context.state_dir) throw new Error("state-dir-does-not-match-target");
      validateContainedPath(path.resolve(args.issue), context.state_dir);
      if (!isImportPathVisible(context, path.resolve(args.issue))) throw new Error("import-pending");
      ensureStorage(context);
      args["state-dir"] = context.state_dir;
      const applied = await withStorageLock(context, () => applyIssue(loadIssue(args.issue, args), args.issue, args));
      writeJson(applied.result, applied.status);
    }
  } catch (error) {
    if (error.code === "invalid-config") writeJson({ status: "invalid-args", reason: "invalid-config" }, 64);
    writeJson({ status: "error", reason: error.message }, 1);
  }

  writeJson({ status: "invalid-args", reason: "unknown-command" }, 64);
}

main();
